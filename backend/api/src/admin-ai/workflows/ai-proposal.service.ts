import {
  ConflictException,
  ForbiddenException,
  GoneException,
  HttpException,
  Injectable,
  Logger,
  NotFoundException,
} from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { AiProposalStatus, AuditAction, Prisma, type AiActionProposal } from '@prisma/client';
import { createHash } from 'node:crypto';
import { AuditLogService } from '../../audit-log/audit-log.service';
import type { AuthenticatedUser } from '../../auth/types/authenticated-user.interface';
import { PrismaService } from '../../prisma/prisma.service';
import type { AdminAiConfig } from '../admin-ai.config';
import { AiPolicyService } from '../control-plane/ai-policy.service';
import { ToolRegistryService } from '../tools/tool-registry.service';
import type { AiActionDraft } from '../tools/ai-tool.types';

export const PROPOSAL_ENTITY = 'AiActionProposal';

export interface ProposalView {
  id: string;
  conversationId: string;
  actionType: string;
  summary: string;
  params: unknown;
  paramsHash: string;
  status: 'pending' | 'executing' | 'executed' | 'failed' | 'rejected' | 'expired';
  expiresAt: Date;
  decidedAt: Date | null;
  executedAt: Date | null;
  result: unknown;
  errorMessage: string | null;
  createdAt: Date;
}

/** Deterministic JSON (sorted keys) so the hash only depends on the values. */
export function stableStringify(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(',')}]`;
  if (value && typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>)
      .filter(([, v]) => v !== undefined)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${stableStringify(v)}`).join(',')}}`;
  }
  return JSON.stringify(value);
}

export function hashProposal(actionType: string, params: unknown): string {
  return createHash('sha256').update(stableStringify({ actionType, params })).digest('hex');
}

/**
 * Human-approval workflow. A proposal is the exact action + parameters the
 * admin reviews; approval must quote its hash, and executes those stored
 * parameters (never anything re-generated by the model) at most once, through
 * the existing domain service, after re-running every check.
 */
@Injectable()
export class AiProposalService {
  private readonly logger = new Logger(AiProposalService.name);
  private readonly config: AdminAiConfig;

  constructor(
    configService: ConfigService,
    private readonly prisma: PrismaService,
    private readonly registry: ToolRegistryService,
    private readonly policy: AiPolicyService,
    private readonly auditLog: AuditLogService,
  ) {
    this.config = configService.get<AdminAiConfig>('adminAi') as AdminAiConfig;
  }

  /** Called by the dispatcher for `propose` tools. Validation failures throw 4xx HttpExceptions. */
  async create(
    user: AuthenticatedUser,
    draft: AiActionDraft,
    refs: { conversationId: string; runId: string },
  ): Promise<ProposalView> {
    const allowed = this.policy.canExecuteProposals(user);
    if (!allowed.allowed) throw new ForbiddenException(allowed.reason);

    const handler = this.registry.findAction(draft.actionType);
    if (!handler) throw new NotFoundException('Unknown action type');

    const params = handler.schema.parse(draft.params) as Record<string, unknown>;
    const summary = await handler.preview(params, user);

    const proposal = await this.prisma.aiActionProposal.create({
      data: {
        conversationId: refs.conversationId,
        runId: refs.runId,
        requestedById: user.id,
        actionType: handler.type,
        params: params as Prisma.InputJsonValue,
        paramsHash: hashProposal(handler.type, params),
        summary,
        expiresAt: new Date(Date.now() + this.config.proposalTtlMinutes * 60_000),
      },
    });

    await this.auditLog.log({
      actorId: user.id,
      action: AuditAction.CREATE,
      entityType: PROPOSAL_ENTITY,
      entityId: proposal.id,
      metadata: { actionType: handler.type, runId: refs.runId },
    });

    return toView(proposal);
  }

  async get(user: AuthenticatedUser, id: string): Promise<ProposalView> {
    return toView(await this.expireIfDue(await this.findOwned(user, id)));
  }

  async listForConversation(user: AuthenticatedUser, conversationId: string): Promise<ProposalView[]> {
    const rows = await this.prisma.aiActionProposal.findMany({
      where: { conversationId, requestedById: user.id },
      orderBy: { createdAt: 'asc' },
    });
    return Promise.all(rows.map(async (row) => toView(await this.expireIfDue(row))));
  }

  async approve(user: AuthenticatedUser, id: string, paramsHash: string): Promise<ProposalView> {
    const allowed = this.policy.canExecuteProposals(user);
    if (!allowed.allowed) throw new ForbiddenException(allowed.reason);

    const proposal = await this.expireIfDue(await this.findOwned(user, id));
    if (proposal.status === AiProposalStatus.EXPIRED) {
      throw new GoneException('This proposal has expired. Ask the assistant to prepare it again.');
    }
    if (proposal.status !== AiProposalStatus.PENDING) {
      throw new ConflictException(`This proposal is already ${proposal.status.toLowerCase()}.`);
    }

    const handler = this.registry.findAction(proposal.actionType);
    if (!handler) throw new ConflictException('This action is no longer available.');

    // The admin approves what they saw: the hash they quote, the hash stored at
    // creation, and a fresh hash of the stored params must all agree.
    const recomputed = hashProposal(proposal.actionType, proposal.params);
    if (paramsHash !== proposal.paramsHash || recomputed !== proposal.paramsHash) {
      throw new ConflictException('The proposal changed after it was reviewed. Review it again before approving.');
    }

    // Single-use claim: only one approval can move PENDING -> EXECUTING.
    const claimed = await this.prisma.aiActionProposal.updateMany({
      where: { id, status: AiProposalStatus.PENDING, expiresAt: { gt: new Date() } },
      data: { status: AiProposalStatus.EXECUTING, decidedById: user.id, decidedAt: new Date() },
    });
    if (claimed.count === 0) {
      throw new ConflictException('This proposal was already decided or has expired.');
    }

    let finalRow: AiActionProposal;
    try {
      const params = handler.schema.parse(proposal.params) as Record<string, unknown>;
      await handler.preview(params, user); // business rules re-checked against current data
      const result = await handler.execute(params, user);
      finalRow = await this.prisma.aiActionProposal.update({
        where: { id },
        data: {
          status: AiProposalStatus.EXECUTED,
          executedAt: new Date(),
          result: result as Prisma.InputJsonValue,
        },
      });
    } catch (error) {
      const message =
        error instanceof HttpException ? error.message : 'The action failed. Nothing was confirmed as changed.';
      if (!(error instanceof HttpException)) {
        this.logger.error(`AI proposal ${id} (${proposal.actionType}) failed`, (error as Error)?.stack);
      }
      finalRow = await this.prisma.aiActionProposal.update({
        where: { id },
        data: { status: AiProposalStatus.FAILED, errorMessage: message },
      });
    }

    await this.auditLog.log({
      actorId: user.id,
      action: AuditAction.UPDATE,
      entityType: PROPOSAL_ENTITY,
      entityId: id,
      metadata: { decision: 'approved', actionType: proposal.actionType, outcome: finalRow.status },
    });

    return toView(finalRow);
  }

  async reject(user: AuthenticatedUser, id: string, note?: string): Promise<ProposalView> {
    await this.findOwned(user, id);
    const updated = await this.prisma.aiActionProposal.updateMany({
      where: { id, status: AiProposalStatus.PENDING },
      data: {
        status: AiProposalStatus.REJECTED,
        decidedById: user.id,
        decidedAt: new Date(),
        decisionNote: note?.slice(0, 500) ?? null,
      },
    });
    if (updated.count === 0) throw new ConflictException('This proposal was already decided.');

    await this.auditLog.log({
      actorId: user.id,
      action: AuditAction.UPDATE,
      entityType: PROPOSAL_ENTITY,
      entityId: id,
      metadata: { decision: 'rejected' },
    });
    return this.get(user, id);
  }

  private async findOwned(user: AuthenticatedUser, id: string): Promise<AiActionProposal> {
    const proposal = await this.prisma.aiActionProposal.findFirst({ where: { id, requestedById: user.id } });
    if (!proposal) throw new NotFoundException('Proposal not found');
    return proposal;
  }

  private async expireIfDue(proposal: AiActionProposal): Promise<AiActionProposal> {
    if (proposal.status !== AiProposalStatus.PENDING || proposal.expiresAt > new Date()) return proposal;
    await this.prisma.aiActionProposal.updateMany({
      where: { id: proposal.id, status: AiProposalStatus.PENDING },
      data: { status: AiProposalStatus.EXPIRED },
    });
    return { ...proposal, status: AiProposalStatus.EXPIRED };
  }
}

function toView(row: AiActionProposal): ProposalView {
  return {
    id: row.id,
    conversationId: row.conversationId,
    actionType: row.actionType,
    summary: row.summary,
    params: row.params,
    paramsHash: row.paramsHash,
    status: row.status.toLowerCase() as ProposalView['status'],
    expiresAt: row.expiresAt,
    decidedAt: row.decidedAt,
    executedAt: row.executedAt,
    result: row.result,
    errorMessage: row.errorMessage,
    createdAt: row.createdAt,
  };
}
